// -------------------------------------------------------------
// INTERNAL VALIDATION FUNCTION (Zero-Error Verification Engine)
// -------------------------------------------------------------
export interface ValidationResult {
  passed: boolean;
  equipmentCount: number;
  temperatureCount: number;
  controllerCount: number;
  hasT201: boolean;
  hasT202: boolean;
  hasFRCA105: boolean;
  hasFRCA103: boolean;
  hasFRCA107: boolean;
  duplicateTags: string[];
  missingCriticalItems: string[];
}

export function validateAmmoniaPlantData(): ValidationResult {
  const tags = new Set<string>();
  const duplicateTags: string[] = [];
  const missingCritical: string[] = [];

  MASTER_EQUIPMENT_DATA.forEach((eq) => {
    if (tags.has(eq.tag)) {
      duplicateTags.push(eq.tag);
    }
    tags.add(eq.tag);
  });

  const hasT201 = MASTER_EQUIPMENT_DATA.some((e) => e.id === 't-201' || e.tag === 'T-201');
  const hasT202 = MASTER_EQUIPMENT_DATA.some((e) => e.id === 't-202' || e.tag === 'T-202');
  const hasFRCA105 = MASTER_CONTROLLER_POINTS.some((c) => c.tag === 'FRCA-105');
  const hasFRCA103 = MASTER_CONTROLLER_POINTS.some((c) => c.tag === 'FRCA-103');
  const hasFRCA107 = MASTER_CONTROLLER_POINTS.some((c) => c.tag === 'FRCA-107');

  if (!hasT201) missingCritical.push('T-201 (Catacarb Absorber Tower)');
  if (!hasT202) missingCritical.push('T-202 (Catacarb Stripper / Desorption Tower)');
  if (!hasFRCA105) missingCritical.push('FRCA-105 (Natural Gas Controller)');
  if (!hasFRCA103) missingCritical.push('FRCA-103 (Steam Controller)');
  if (!hasFRCA107) missingCritical.push('FRCA-107 (Air Controller)');

  const passed = duplicateTags.length === 0 && missingCritical.length === 0;

  return {
    passed,
    equipmentCount: MASTER_EQUIPMENT_DATA.length,
    temperatureCount: MASTER_TEMPERATURE_POINTS.length,
    controllerCount: MASTER_CONTROLLER_POINTS.length,
    hasT201,
    hasT202,
    hasFRCA105,
    hasFRCA103,
    hasFRCA107,
    duplicateTags,
    missingCriticalItems: missingCritical,
  };
}
